def test_media_operations_are_agent_callable(env, source_asset):
    """F-2: producing a file is drafting, not publishing. Nothing here spends,
    publishes, or clears a rights flag."""
    for name in MEDIA_OPS:
        assert OPERATIONS[name].authority == "agent", f"{name} unexpectedly needs the operator"


def test_project_mutations_declare_their_entity_so_they_lock(env):
    """Locking is derived from the registry, not written per operation."""
    from promedia.core.registry import lock_target

    for name in ("create-project", "set-edl", "render-project"):
        assert OPERATIONS[name].mutates and OPERATIONS[name].entity == "project"
    # create-project has no project_id yet, so it takes no lock — nothing exists
    # for another agent to be holding.
    assert lock_target(OPERATIONS["create-project"], {}) is None
    assert lock_target(OPERATIONS["set-edl"], {"project_id": "p1"}) == ("project", "p1")
    assert lock_target(OPERATIONS["render-project"], {"project_id": "p1"}) == ("project", "p1")


def test_read_only_media_operations_take_no_lock(env):
    from promedia.core.registry import lock_target

    for name in ("project", "list-projects", "project-versions", "renders",
                 "media-capabilities"):
        assert lock_target(OPERATIONS[name], {"project_id": "p1"}) is None


def test_capabilities_reports_what_cannot_be_generated(env):
    """The requirement that a missing capability names what it needs rather
    than being discovered as a failure."""
    cfg, ctx = env
    caps = invoke(ctx, "media-capabilities", {})
    assert caps["ffmpeg_available"] is ffmpeg.available()
    assert {"dissolve", "fade", "cut"} <= set(caps["transitions"])
    missing = {item["capability"] for item in caps["not_available"]}
    assert "video generation" in missing
    for item in caps["not_available"]:
        assert item["needs"], f"{item['capability']} does not say what it needs"
    assert all(s["fabrication"] == "F-003" for s in caps["known_substitutions"])


def test_every_advertised_transition_is_either_implemented_or_reported(env):
    """The defect an independent audit found in F-003's first version.

    edl.validate() REJECTS a transition outside its vocabulary, so accepting one
    is an active promise that it is supported. Four of the seven emit no filter
    at all and render as hard cuts while reporting success — worse than the
    dissolve case, which at least produces a visible effect.

    Asserted as a rule over the whole vocabulary rather than a list of known-bad
    names, so a transition added to the EDL tomorrow is covered the day it is
    added. A hand-written list is exactly what drifted the first time.
    """
    from promedia.core.media.edl import TRANSITIONS
    from promedia.core.media.render import TRANSITION_REALITY

    assert set(TRANSITIONS) == set(TRANSITION_REALITY), (
        "a transition is advertised by the EDL but the renderer does not say "
        "what it really does — implement it, or record the substitution"
    )


