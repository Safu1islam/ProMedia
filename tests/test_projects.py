# --- locking, authority, and the registry ------------------------------------


@needs_ffmpeg
def test_a_second_agent_cannot_render_the_same_project_concurrently(env, source_asset, monkeypatch):
    """C-19. A render reads the edit and runs for minutes; without the lock, an
    edit changed mid-render yields an output attributed to a version it did not
    come from."""
    from promedia.core import projects as projects_layer
    from promedia.errors import EntityLocked

    cfg, ctx = env
    pid = invoke(ctx, "create-project", {"title": "P"})["project_id"]
    invoke(ctx, "set-edl", {"project_id": pid, "edl": an_edl(source_asset)})

    other = db.connect(cfg.db_path)
    beta = Context(config=cfg, conn=other, principal=agent("b"), agent_id="agent-b")
    seen = {}
    real = projects_layer._resolve_sources

    def probe(inner_ctx, document):
        if inner_ctx.agent_id == "agent-a":
            try:
                invoke(beta, "render-project", {"project_id": pid})
            except Exception as exc:  # noqa: BLE001 — which one is the point
                seen["error"] = exc
        return real(inner_ctx, document)

    monkeypatch.setattr(projects_layer, "_resolve_sources", probe)
    invoke(ctx, "render-project", {"project_id": pid, "quality": "fast"})
    other.close()

    assert isinstance(seen.get("error"), EntityLocked), f"got {seen.get('error')!r}"
    assert seen["error"].detail["entity_type"] == "project"
    assert seen["error"].detail["owner"] == "agent-a"


