"""T-042 — projects, EDL versioning, and the media operations.

T-041 built an engine that no surface could reach. These tests are about the
thing that closes that: a project holds a versioned edit, and every media
capability is a registered operation, so the agent and the operator drive the
same code through the same authority and locking rules as everything else.

The append-only version model is the part worth pinning hardest. It is what
makes an agent's autonomous edit safe to accept — the previous version is always
recoverable — and what lets an operator ask "what did it change" and get an
answer from the data rather than from a summary written by the thing that
changed it.
"""

