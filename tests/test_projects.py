def test_editing_appends_a_version_and_the_previous_one_survives(env, source_asset):
    """AC-1, and the property that makes an agent's edit safe to accept."""
    cfg, ctx = env
    pid = invoke(ctx, "create-project", {"title": "P"})["project_id"]

    first = invoke(ctx, "set-edl", {"project_id": pid, "edl": an_edl(source_asset),
                                    "note": "first cut"})
    second = invoke(ctx, "set-edl", {
        "project_id": pid,
        "edl": an_edl(source_asset, aspect="vertical", text=[{"text": "Title"}]),
        "note": "went vertical",
    })

    assert (first["edl_version"], second["edl_version"]) == (2, 3)
    # The earlier edit is still there, unchanged.
    old = invoke(ctx, "project", {"project_id": pid, "version": 2})
    assert old["aspect"] == "landscape_720" and old["text_overlays"] == 0
    assert invoke(ctx, "project", {"project_id": pid})["aspect"] == "vertical"


def test_the_history_records_who_shaped_each_edit(env, source_asset):
    """'Did a human or an agent make this edit' is what an operator asks before
    approving what came out of it — the same reasoning that put authorship on
    rights declarations."""
    cfg, ctx = env
    pid = invoke(ctx, "create-project", {"title": "P"})["project_id"]
    invoke(ctx, "set-edl", {"project_id": pid, "edl": an_edl(source_asset)})

    op_ctx = Context(config=cfg, conn=ctx.conn, principal=operator("op"))
    invoke(op_ctx, "set-edl", {"project_id": pid, "edl": an_edl(source_asset),
                               "note": "operator tweak"})

    history = invoke(ctx, "project-versions", {"project_id": pid})["versions"]
    assert [v["version"] for v in history] == [3, 2, 1]
    assert history[0]["authored_kind"] == "operator"
    assert history[0]["note"] == "operator tweak"
    assert history[1]["authored_kind"] == "agent"


def test_an_invalid_edit_is_refused_and_not_stored(env, source_asset):
    """A stored version is one an operator may later restore. Storing an
    unrenderable one is a trap with a delay on it."""
    cfg, ctx = env
    pid = invoke(ctx, "create-project", {"title": "P"})["project_id"]
    bad = an_edl(source_asset)
    bad["clips"][0]["end"] = -5

    with pytest.raises(ValidationError):
        invoke(ctx, "set-edl", {"project_id": pid, "edl": bad})
    assert invoke(ctx, "project", {"project_id": pid})["edl_version"] == 1


