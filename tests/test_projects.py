def an_edl(asset_id, **kw):
    base = {"aspect": "landscape_720",
            "clips": [{"asset_id": asset_id, "start": 0, "end": 1}]}
    base.update(kw)
    return base


# --- the version model -------------------------------------------------------


def test_a_new_project_starts_with_a_readable_empty_edit(env):
    """Version 1 exists immediately, so no caller ever handles 'no version yet'."""
    cfg, ctx = env
    created = invoke(ctx, "create-project", {"title": "  Launch teaser  "})
    assert created["edl_version"] == 1
    assert created["title"] == "Launch teaser", "title should be trimmed"

    current = invoke(ctx, "project", {"project_id": created["project_id"]})
    assert current["clips"] == 0 and current["edl_version"] == 1


